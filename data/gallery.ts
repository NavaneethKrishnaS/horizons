/*
  The gallery, as data.

  Two hundred and sixty-two photographs from journeys this company
  planned, taken by the people who were on them. They came out of the
  Scenic Escapes library, which is the same company's, and were cut down
  from four hundred and forty-three: what went were the frames too dark
  or too soft to survive at any size, the ones with no subject in them,
  and the runs of near-identical shots, of which the best was kept.

  Every photograph exists at more than one width. The smallest is listed
  first and is what the grid asks for; next/image picks a size from
  there, so no file here is ever sent at more than the grid needs.

  The alt text describes what is in the frame rather than repeating the
  place name, because a screen reader given "Munnar" fifteen times has
  been told nothing, and so has Google.
*/

